import { chromium } from 'playwright';
const browser = await chromium.launch({args:['--use-gl=angle','--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1180,height:760}});
const errors=[];
page.on('pageerror',e=>errors.push('page: '+e.message));
page.on('console',m=>{if(m.type()==='error') errors.push('console: '+m.text())});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded',timeout:90000});
await page.locator('.spin-slow').waitFor({state:'detached',timeout:120000});
await page.waitForTimeout(2500);
await page.screenshot({path:'/tmp/final-day.png',timeout:150000});
await page.locator('button[aria-label="Switch to night"]').click();
await page.waitForTimeout(5000);
await page.screenshot({path:'/tmp/final-night.png',timeout:150000});
await page.locator('button[aria-label="Switch to day"]').click();
await page.locator('button[aria-label="Jet On"]').click();
await page.waitForTimeout(500);
const jet={off:await page.locator('button[aria-label="Jet Off"]').count(),joystick:await page.locator('[aria-label="Movement joystick"]').count(),altitude:await page.locator('[aria-label="Jet altitude control"]').count(),clap:await page.locator('button[aria-label="Clap"]').count(),dayNight:await page.locator('button[aria-label="Switch to night"]').count()};
const alt=page.locator('[aria-label="Jet altitude control"]');const r=await alt.boundingBox();
await page.mouse.move(r.x+r.width/2,r.y+r.height/2);await page.mouse.down();await page.mouse.move(r.x+r.width/2,r.y+8,{steps:6});
await page.waitForTimeout(1800);await page.mouse.up();
await page.screenshot({path:'/tmp/final-jet.png',timeout:150000});
console.log(JSON.stringify({jet,errors}));
await browser.close();
